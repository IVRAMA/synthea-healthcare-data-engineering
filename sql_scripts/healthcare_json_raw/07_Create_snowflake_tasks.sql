ALTER TASK SP_LOAD_SILVER_DATA RESUME;
ALTER TASK SP_APPLY_SCHEMA_CHANGES RESUME; 
ALTER TASK L1_TO_L2_MERGE RESUME; 
ALTER TASK MASTER_TO_L1_MERGE RESUME;

